#!/bin/bash
# hcpost-boot.sh — one A/B arm of the SYCL hc_post fusion benchmark on Apollo.
# Modeled on glm53-lcpp-tests/glm53-boot.sh (same ops-policy compliance: scratch
# under /home/llm/hcpost-tests/, unique container name/port, dmesg + container
# logs captured, no --rm, no numerics changes, models mounted read-only).
#
# Usage (on Apollo): MODEL=glm|qwen FUSION=1|0 TAG=t1 bash hcpost-boot.sh
#   IMG   (default registry.wormley.com/ai/llama.cpp-intel:hc-post-fusion)
#   TAG   selects port (glm: 18410+NN, qwen: 18420+NN) and scratch dir
set -u
MODEL="${MODEL:?glm|qwen}"
FUSION="${FUSION:?0|1}"
TAG="${TAG:?e.g. t1}"
IMG="${IMG:-registry.wormley.com/ai/llama.cpp-intel:hc-post-fusion}"

BASEROOT=/home/llm/hcpost-tests
BASE="$BASEROOT/$MODEL-f$FUSION-$TAG"
NAME="hcpost-$MODEL-f$FUSION-$TAG"
SUMMARY="$BASEROOT/summary.txt"
mkdir -p "$BASE/cache" "$BASE/tmp" "$BASE/outputs"; export TMPDIR="$BASE/tmp"

NN=${TAG//[!0-9]/}; [ -z "$NN" ] && NN=99
if [ "$MODEL" = glm ]; then PORT=$((18410 + NN)); else PORT=$((18420 + NN)); fi
if ss -ltn | grep -q ":$PORT "; then
  echo "hcpost-$NAME PORT $PORT ALREADY IN USE — pick another TAG" | tee -a "$SUMMARY"; exit 1
fi
for c in $(podman ps --format '{{.Names}}' | grep -E '^hcpost-' || true); do
  podman stop "$c" >/dev/null 2>&1
done

MOUNTS="" ; MARGS="" ; ALIAS=""
if [ "$MODEL" = glm ]; then
  MOUNTS="-v /models/GLM-5.3-Flash-GGUF:/models/GLM-5.3-Flash-GGUF:ro"
  # metadata-only archfix shard (generated by an earlier session, read-only overlay)
  PATCH=/home/llm/qwen38-tests/glm53-lcpp/gguf-patched/UD-Q4_K_XL/GLM-5.3-Flash-UD-Q4_K_XL-00001-of-00006.gguf
  MOUNTS="$MOUNTS -v $PATCH:/models/GLM-5.3-Flash-GGUF/UD-Q4_K_XL/GLM-5.3-Flash-UD-Q4_K_XL-00001-of-00006.gguf:ro"
  MARGS="--model /models/GLM-5.3-Flash-GGUF/UD-Q4_K_XL/GLM-5.3-Flash-UD-Q4_K_XL-00001-of-00006.gguf \
    --n-gpu-layers 24 --reasoning on --alias glm53"
  ALIAS=glm53 ; CTARGS='{"reasoning_effort":"low"}'
elif [ "$MODEL" = qwen ]; then
  MOUNTS="-v /models/Qwen3.8-Flash-Next-GGUF:/models/Qwen3.8-Flash-Next-GGUF:ro"
  MARGS="--model /models/Qwen3.8-Flash-Next-GGUF/Q8_0/Q8_0/Qwen3.8-Flash-Next-Q8_0-00001-of-00006.gguf \
    --model-draft /models/Qwen3.8-Flash-Next-GGUF/MTP/mtp-Qwen3.8-Flash-Next-Q8_0.gguf \
    --n-gpu-layers 30 --cache-type-k q8_0 --cache-type-v q8_0 \
    --override-tensor per_layer_token_embd=CPU,ple_ngram_embd=CPU \
    --reasoning-preserve --reasoning on --alias qwen38"
  ALIAS=qwen38 ; CTARGS='{"enable_thinking":false}'
else
  echo "MODEL must be glm|qwen" | tee -a "$SUMMARY"; exit 1
fi

dmesg -wT > "$BASE/dmesg-live.log" 2>&1 &
DMESG_PID=$!

podman run -d --name "$NAME" --group-add keep-groups \
  --device /dev/dri -v /dev/dri/by-path:/dev/dri/by-path --network=host \
  --shm-size=2g --ulimit memlock=-1:-1 \
  -e GGML_SYCL_FA_ONEDNN=1 -e SYCL_CACHE_PERSISTENT=0 -e ZES_ENABLE_SYSMAN=1 \
  -e CCL_P2P_ENABLE=1 -e CCL_D2D=p2p \
  -e GGML_SYCL_ENABLE_FUSION="$FUSION" \
  $MOUNTS \
  -v "$BASE/cache:/cache:rw" \
  "$IMG" \
  --cache-ram 32768 --jinja \
  $MARGS \
  --ctx-checkpoints 8 -np 1 --cache-reuse 512 \
  --ctx-size 262144 \
  --fit off --batch-size 2048 --ubatch-size 512 \
  --flash-attn on \
  --spec-type draft-mtp --spec-draft-n-max 3 \
  --host 0.0.0.0 --port "$PORT" --log-colors off \
  > "$BASE/run.out" 2>&1
podman logs -f "$NAME" > "$BASE/container.log" 2>&1 &
LOG_PID=$!

HB=""
for i in $(seq 1 720); do
  curl -sf "http://127.0.0.1:$PORT/health" >/dev/null 2>&1 && HB=$((i*5)) && break
  podman ps --format '{{.Names}}' | grep -qx "$NAME" || break
  sleep 5
done

if [ -z "${HB:-}" ]; then
  echo "hcpost-$NAME BOOT_FAIL" >> "$SUMMARY"
  grep -E "error|Error|failed|DEVICE_LOST|UR_RESULT|out of memory|OOM|Exception" \
    "$BASE/container.log" | tail -15 | sed 's/^/  /' >> "$SUMMARY"
  dmesg -T > "$BASE/dmesg-exit.log" 2>/dev/null || true
  podman logs "$NAME" > "$BASE/container-final.log" 2>&1
  podman ps --format '{{.Names}}' | grep -qx "$NAME" && podman stop "$NAME" >/dev/null 2>&1
  kill $LOG_PID $DMESG_PID 2>/dev/null || true
  exit 1
fi
echo "hcpost-$NAME IMG=$IMG FUSION=$FUSION health=${HB}s" >> "$SUMMARY"

# fused-op resolution evidence: did the fused hc_post path survive the hybrid split?
grep -E "resolving fused DeepSeek|fused DeepSeek V4 HC (pre|comb|post) (enabled|not supported)" \
  "$BASE/container.log" | sed 's/^/hcpost-'"$NAME"' FUSEDOP /' >> "$SUMMARY"

python3 "$(dirname "$0")/hcpost-bm.py" "$PORT" "$NAME" "$ALIAS" "$CTARGS" "$BASE/outputs" \
  2>&1 | tee -a "$SUMMARY"

podman logs "$NAME" > "$BASE/container-final.log" 2>&1
dmesg -T > "$BASE/dmesg-exit.log" 2>/dev/null || true
echo "hcpost-$NAME UR=$(grep -c UR_RESULT "$BASE/container.log" || true) faults_live=$(grep -icE 'fault response|timedout|engine reset' "$BASE/dmesg-live.log" 2>/dev/null || true)" >> "$SUMMARY"

# authoritative per-request numbers: server-side print_timing lines, in order
python3 - "$BASE/container.log" "$NAME" "$SUMMARY" <<'EOF'
import re, sys
log, name, summary = open(sys.argv[1], errors="replace").read(), sys.argv[2], sys.argv[3]
reqs = ["arith", "decode-d1", "decode-d2", "decode-d3", "prefill-pA", "prefill-pB"]
pe, ev = [], []
for line in log.splitlines():
    if "prompt eval time" in line:
        m = re.search(r"/\s*(\d+) tokens \(.*?,\s*([\d.]+) tokens per second", line)
        if m: pe.append((m.group(1), float(m.group(2))))
    elif "eval time" in line:
        m = re.search(r"/\s*(\d+) tokens \(.*?,\s*([\d.]+) tokens per second", line)
        if m: ev.append((m.group(1), float(m.group(2))))
with open(summary, "a") as f:
    for i, rq in enumerate(reqs):
        if i < len(pe): f.write("hcpost-%s SERVER %s prefill %.1f tok/s (%s tok)\n" % (name, rq, pe[i][1], pe[i][0]))
        if i < len(ev): f.write("hcpost-%s SERVER %s gen %.1f tok/s (%s tok)\n" % (name, rq, ev[i][1], ev[i][0]))
EOF

podman ps --format '{{.Names}}' | grep -qx "$NAME" && podman stop "$NAME" >/dev/null 2>&1
kill $LOG_PID $DMESG_PID 2>/dev/null || true
